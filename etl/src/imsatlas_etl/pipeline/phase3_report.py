"""Human-facing Phase 3 report per new variable."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from imsatlas_etl.catalog import load_catalog
from imsatlas_etl.connectors.country_index import SOURCE_LANDING
from imsatlas_etl.pipeline.coverage import NEW_VARIABLE_IDS
from imsatlas_etl.pipeline.io_paths import curated_dir, status_root
from imsatlas_etl.pipeline.variables_build import VARIABLE_SPECS
from imsatlas_etl.rights import gate_for_variable, load_deployment
from imsatlas_etl.sources import sources_by_id


def build_phase3_report(*, root: Path | None = None) -> str:
    catalog = {v["id"]: v for v in load_catalog()["variables"]}
    registry = sources_by_id()
    deployment = load_deployment()
    meta_path = curated_dir(root=root) / "variables_country_year.meta.json"
    meta: dict[str, Any] = {}
    if meta_path.is_file():
        meta = json.loads(meta_path.read_text(encoding="utf-8"))

    lines = [
        "# Phase 3 — new variables report",
        "",
        "Generated by `atlas-etl phase3-report`.",
        "",
        (
            "| Variable | Source | Years | Countries | Licence | Gate | "
            "BYOD/ship | Issues |"
        ),
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for vid in NEW_VARIABLE_IDS:
        var = catalog.get(vid, {})
        spec = VARIABLE_SPECS.get(vid, {})
        source_id = spec.get("source_id", "?")
        source = registry.get(source_id, {})
        rights = (source.get("rights") or {}) if source else {}
        licence = rights.get("licence_id", "UNKNOWN")
        gate = (
            gate_for_variable(var, registry=registry, deployment=deployment)
            if var
            else {"decision": "byod_only", "reasons": ["missing catalog entry"]}
        )
        vmeta = (meta.get("variables") or {}).get(vid, {})
        years = vmeta.get("years") or var.get("years") or []
        countries = vmeta.get("countries") or []
        n_unmatched = vmeta.get("n_unmatched", 0)
        landing = SOURCE_LANDING.get(source_id, {})
        shippable = gate["decision"] in {"ship_raw", "ship_derived"}
        byod = "ship" if shippable else "BYOD"
        issues = []
        if n_unmatched:
            issues.append(f"{n_unmatched} unmatched names")
        if landing.get("notes"):
            issues.append(str(landing["notes"])[:80])
        if var.get("series_breaks"):
            issues.append(f"series_breaks={var['series_breaks']}")
        year_s = ",".join(str(y) for y in years) if years else "—"
        n_c = len(countries) if countries else "—"
        iss = "; ".join(issues).replace("|", "\\|") or "—"
        lines.append(
            f"| {vid} | {source_id} | {year_s} | {n_c} | {licence} | "
            f"{gate['decision']} | {byod} | {iss} |",
        )
    lines.extend(
        [
            "",
            "## Access notes",
            "",
        ],
    )
    for sid, info in SOURCE_LANDING.items():
        lines.append(
            f"- `{sid}`: {info['landing_url']} (accessed {info['access_date']}). "
            f"{info['notes']}",
        )
    lines.append("")
    return "\n".join(lines)


def write_phase3_report(*, root: Path | None = None) -> Path:
    text = build_phase3_report(root=root)
    out = status_root(root=root)
    out.mkdir(parents=True, exist_ok=True)
    path = out / "phase3_variables.md"
    path.write_text(text, encoding="utf-8")
    return path
